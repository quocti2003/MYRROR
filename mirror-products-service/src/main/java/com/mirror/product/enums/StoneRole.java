package com.mirror.product.enums;

/**
 * Role classification for stones in a jewelry piece
 */
public enum StoneRole {
    MAIN,       // Primary center stone
    MAIN_2,     // Secondary main stone (for multi-stone designs)
    SIDE,       // Side accent stones
    SIDE_2,     // Additional side stones
    MELEE       // Small accent/pave stones
}

package com.mirror.product.enums;

/**
 * Color category classification for stones
 * Determines which color-related fields are applicable
 */
public enum StoneColorCategory {
    COLORLESS,      // D-J color grades (traditional diamond grading)
    FANCY_COLOR,    // Fancy colored diamonds (Yellow, Pink, Blue, etc.)
    COLOR_STONE     // Colored gemstones (Ruby, Sapphire, Emerald, etc.)
}

package com.mirror.product.enums;

/**
 * Types of labels that can be printed for products
 */
public enum LabelType {
    JEWELRY_TAG,      // Small tags for jewelry items
    BUTTERFLY_TAG,    // Butterfly-shaped hanging tags
    PRODUCT_LABEL,    // Standard product labels
    QR_CODE,          // QR code labels
    BARCODE,          // Barcode-only labels
    PRICE_TAG         // Price tag labels
}

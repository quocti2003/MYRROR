package com.mirror.product.enums;

/**
 * Labor type classification for JTRC cost components
 */
public enum JTRCLaborType {
    CASTING,    // Metal casting (lost-wax, etc.)
    SETTING,    // Stone setting labor
    POLISHING,  // Polishing and buffing
    FINISHING,  // Metal finishing (texturing, etc.)
    ENGRAVING,  // Engraving and inscription
    PLATING,    // Metal plating (rhodium, gold plating)
    ASSEMBLY,   // Assembly of components
    OTHER       // Other labor costs
}
